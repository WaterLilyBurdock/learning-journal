import numpy as np
#.reshape(2, 4, 6) - перестраивает его в трёхмерных массив

#Доступ и нарезка (индексация)
arr = np.arange(48).reshape(2,4,6) #Массив 48 должен быть равен произведению чисел reshap 2*4*6
print(arr)
print("Первая матрциа")
print(arr[0]) #достаём первую матрицу
print("#3 строка второй матрицы")
print(arr[1,2]) #3 строка второй матрицы
print("первая строка из ОБЕИХ картинок, форма (2, 6)")
print(arr[:, 0, :]) 
print("первый столбец первой картинки, форма (4,)")
print(arr[0, :, 0]) 
print("последний столбец обеих картинок, форма (2, 4) ")
print(arr[:, :, -1])
print(arr[0,2,4])
          
#Агрегации по осям (ключевой навык)
print(arr.mean(axis=0).shape)   # (4, 6) — среднее между двумя картинками потому что они дают 24
print(arr.mean(axis=1).shape)   # (2, 6) — среднее по строкам каждой картинки
print(arr.mean(axis=2).shape)   # (2, 4) — среднее по столбцам
print(arr.max(axis=(1, 2)).shape)  # (2,)  — максимум в каждой картинке
print(arr.sum())                # скаляр — сумма всего

